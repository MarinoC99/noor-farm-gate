DOC_EXTS = {".md", ".markdown", ".txt", ".html", ".htm"}
GENERATED_MARK = re.compile(r"generated-from:\s*eval/results/latest\.json")
CITE = re.compile(r"\[cite:([^\]]+)\]", re.I)
NUM = r"(?<![\w.\-/])(\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+(?:\.\d+)?)"
RESULT_PATTERNS = [
    ("percentage", re.compile(NUM + r"\s*(?:%|percent\b|pp\b|percentage points?\b)", re.I)),
    ("duration", re.compile(NUM + r"\s*(?:ms|milliseconds?|secs?|seconds?)\b", re.I)),
    ("size", re.compile(NUM + r"\s*[KMGT]i?B\b", re.I)),
    ("score", re.compile(
        r"\b(?:accuracy|chrF\+{0,2}|BLEU|COMET|F1|precision|recall|score|WER|CER|AUC|latency|p50|p90|p95|p99)\b"
        r"\s*(?:[:=≈~]|of|is|was|at|reached|hit)?\s*(?:about|around|approximately|~|≈)?\s*" + NUM, re.I)),
    ("score", re.compile(NUM + r"\s*(?:chrF\+{0,2}|BLEU|COMET|F1|WER|CER)\b", re.I)),
    ("ratio", re.compile(NUM + r"\s*[x×]\s*(?:faster|slower|smaller|larger|fewer|more|better|speed-?up)\b", re.I)),
]


def cited(line: str) -> bool:
    """[cite: source, year, country] on the line, as CLAUDE.md asks for problem-framing figures."""
    for m in CITE.finditer(line):
        parts = [p.strip() for p in m.group(1).split(",") if p.strip()]
        if len(parts) >= 3 and any(re.fullmatch(r"(?:19|20)\d{2}", p) for p in parts):
            return True
    return False


def numeric_leaves(obj):
    if isinstance(obj, bool):
        return
    if isinstance(obj, (int, float)):
        yield float(obj)
    elif isinstance(obj, dict):
        for v in obj.values():
            yield from numeric_leaves(v)
    elif isinstance(obj, list):
        for v in obj:
            yield from numeric_leaves(v)


def in_results(token: str, values: list[float]) -> bool:
    """True if the figure as printed is some value in latest.json, rounded to the printed
    precision, directly or as fraction->%, bytes->MB/MiB, or s<->ms."""
    n = float(token.replace(",", ""))
    d = len(token.split(".")[1]) if "." in token else 0
    tolerance = 0.5 * 10 ** -d + 1e-9
    return any(abs(cand - n) <= tolerance
               for v in values
               for cand in (v, v * 100, v / 1e6, v / 2 ** 20, v * 1000, v / 1000))


def check_numbers(c: Check) -> None:
    files = [README] if README.exists() else []
    if DOCS.exists():
        files += [p for p in walk(DOCS) if p.suffix.lower() in DOC_EXTS]
    values: list[float] | None = None
    results_error = None
    for path in files:
        lines = text_lines(path) or []
        generated = any(GENERATED_MARK.search(line) for line in lines[:10])
        if generated and values is None and results_error is None:
            try:
                values = list(numeric_leaves(json.loads(RESULTS.read_text(encoding="utf-8"))))
            except (OSError, json.JSONDecodeError) as e:
                results_error = f"eval/results/latest.json is unreadable: {e}"
        for n, line in enumerate(lines, 1):
            if cited(line):
                continue
            hits = {}
            for label, rx in RESULT_PATTERNS:
                for m in rx.finditer(line):
                    hits.setdefault(m.start(1), (label, m.group(1), m.group(0).strip()))
            for _, (label, token, snippet) in sorted(hits.items()):
                where = f"{rel(path)}:{n}"
                if not generated:
                    c.fail(f"{where}  unsourced {label} {snippet!r}: generate this file from "
                           "eval/results/latest.json, add [cite: source, year, country], or write TODO(measure)")
                elif values is None:
                    c.fail(f"{where}  file says generated-from latest.json, but {results_error}")
                elif not in_results(token, values):
                    c.fail(f"{where}  {snippet!r} does not appear in eval/results/latest.json")
    c.note(f"scanned {len(files)} files (README.md and docs/)")


