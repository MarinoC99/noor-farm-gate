def main() -> int:
    parser = argparse.ArgumentParser(description="Compliance check for CLAUDE.md rules.")
    parser.add_argument("--only", help="comma-separated subset: " + ",".join(k for k, _, _ in CHECKS))
    args = parser.parse_args()
    selected = set(args.only.split(",")) if args.only else {k for k, _, _ in CHECKS}
    unknown = selected - {k for k, _, _ in CHECKS}
    if unknown:
        parser.error(f"unknown checks: {', '.join(sorted(unknown))}")

    results = []
    for key, title, fn in CHECKS:
        if key not in selected:
            continue
        c = Check(key, title)
        fn(c)
        results.append(c)
        print(f"\n[{title}]")
        for msg in c.notes:
            print(f"  note  {msg}")
        for msg in c.failures:
            print(f"  FAIL  {msg}")
        print(f"  -> {'FAIL (%d)' % len(c.failures) if c.failures else 'PASS'}")

    failed = [c for c in results if c.failures]
    print()
    if failed:
        print(f"verify: FAILED {len(failed)} of {len(results)} checks: {', '.join(c.key for c in failed)}")
        return 1
    print(f"verify: all {len(results)} checks passed")
    return 0


