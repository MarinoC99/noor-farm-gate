#!/usr/bin/env python3
"""Compliance check for the Tourism entry. Enforces the rules in CLAUDE.md.

Exits 1 if any check fails, 2 if the check itself cannot run. Run via `make verify`.
Do not edit this file to make a failure go away. If a check is wrong, say why and
wait (CLAUDE.md, "Commands").

  1 network    No network code anywhere in src/ except src/outbox/. The pipeline
               never imports the outbox. Pipeline checks run with the network denied.
  2 budget     Bytes under models/ stay within the budget in CLAUDE.md rule 2.
               No weight files anywhere else in the repo.
  3 templates  config/responses.yaml is well formed, with English and Swahili text
               for every template. Every reply the pipeline emits re-renders exactly
               from a template plus slot values that match the slot's regex. No
               text-generating model on the outbound route (src/pipeline/, src/outbox/).
  4 abstain    The abstain template exists and is reachable. Every case in
               eval/abstain_cases.jsonl returns outcome "abstain".
  5 inventory  Every row of data/INVENTORY.md has source URL, licence, size and
               "does not cover". TODO(human) is allowed in "does not cover" only.
  6 numbers    No result-like figure (%, ms, MB, scores) in docs/ or README.md unless
               the file declares `generated-from: eval/results/latest.json` and the
               figure is in that file, or the line carries
               [cite: source, year, country] for a problem-framing statistic.
  7 route      Every case in eval/route_to_human_cases.jsonl returns outcome
               "route_to_human", which carries no draft at all.
  8 weights    No code under src/ downloads model weights. Weights are in models/
               before the app starts; pipeline checks run with empty model caches.
  9 logging    No logging call in src/ takes a message body. No telemetry or
               crash-report SDK.

Pipeline contract. Checks 3, 4 and 7 drive the pipeline through this, whatever the
app target turns out to be:

  entry point  src/pipeline/cli.py   run as: python -m src.pipeline.cli
          or   src/pipeline/cli.mjs  run as: node src/pipeline/cli.mjs
  stdin        one JSON object per line: {"id": str, "text": str}
  stdout       one JSON object per input line, same order:
               {"id": str, "outcome": "draft" | "abstain" | "route_to_human",
                "template_id": str | null, "lang": str, "slots": {name: value},
                "reply": str | null}
    draft           template_id is a template other than abstain_id. reply is the
                    guest-facing text and must equal templates[template_id].text[lang]
                    with each {slot} substituted.
    abstain         template_id is abstain_id; reply is that template, rendered.
    route_to_human  template_id and reply are null: no draft at all. The app shows a
                    blank compose box under the translated enquiry.
  Extra keys (intent, confidence, the Swahili translation for Noor) are allowed.
  Write replies with sys.stdout.write / process.stdout.write; print() and console.*
  are scanned as logging (check 9). Logs go to stderr and never carry a message body.
"""

