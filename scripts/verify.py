LOG_CALL = re.compile(
    r"(?:\bconsole\.(?:log|info|warn|error|debug|trace)"
    r"|\b(?:logging|logger|log|_log|LOGGER|Log)\.(?:debug|info|warning|warn|error|exception|critical|log|v|d|i|w|e)"
    r"|\bSystem\.(?:out|err)\.print(?:ln|f)?|\bNSLog|\bos_log|\bprint"
    r"|\bsys\.stderr\.write|\bprocess\.stderr\.write)\s*\(")
TELEMETRY = re.compile(
    r"(?:\bimport\b|\bfrom\b|\brequire\s*\()[^\n]*\b(?:sentry|crashlytics|bugsnag|mixpanel|amplitude|posthog"
    r"|datadog|newrelic|appcenter|analytics)\b|\bcapture(?:Exception|Message)\s*\(", re.I)
# Identifier parts that name guest text. Matched on snake_case and camelCase parts.
BODY_WORDS = {"text", "texts", "message", "messages", "msg", "msgs", "body", "enquiry", "enquiries",
              "inquiry", "reply", "replies", "draft", "drafts", "translation", "translated", "guest",
              "sms", "utterance", "content"}
SUBSCRIPT_KEY = re.compile(r"\[\s*(['\"])(\w+)\1\s*\]")
STRING_LIT = re.compile(r"(['\"`])((?:\\.|(?!\1).)*)\1")
INTERPOLATION = re.compile(r"\$?\{([^{}]*)\}")


def code_only(s: str) -> str:
    """Drops string-literal text but keeps what is interpolated or used as a key."""
    s = SUBSCRIPT_KEY.sub(lambda m: "." + m.group(2), s)
    return STRING_LIT.sub(lambda m: " " + " ".join(INTERPOLATION.findall(m.group(2))) + " ", s)


def call_arguments(lines: list[str], n: int, start: int) -> str:
    """Code passed to the call whose '(' ends at lines[n][start], up to ten lines."""
    depth, parts = 1, []
    for k, line in enumerate(lines[n:n + 10]):
        code = code_only(line[start:] if k == 0 else line)
        for j, ch in enumerate(code):
            depth += (ch == "(") - (ch == ")")
            if depth == 0:
                return " ".join(parts + [code[:j]])
        parts.append(code)
    return " ".join(parts)


def body_words(code: str) -> set[str]:
    words = set()
    for ident in re.findall(r"[A-Za-z_]\w*", code):
        words.update(p.lower() for p in re.findall(r"[A-Z]?[a-z]+|[A-Z]+(?![a-z])", ident))
    return words & BODY_WORDS


def check_logging(c: Check) -> None:
    files = src_files()
    for path in files:
        lines = text_lines(path) or []
        for n, line in enumerate(lines):
            where = f"{rel(path)}:{n + 1}"
            if TELEMETRY.search(line):
                c.fail(f"{where}  telemetry or crash-report SDK (captures context, guest text included): "
                       f"{line.strip()[:100]}")
            for m in LOG_CALL.finditer(line):
                hit = body_words(call_arguments(lines, n, m.end()))
                if hit:
                    c.fail(f"{where}  logging call takes a message body ({', '.join(sorted(hit))}): "
                           f"{line.strip()[:100]}")
    c.note(f"scanned {len(files)} source files under src/")


